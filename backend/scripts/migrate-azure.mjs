async function manifest(client){
 const tables=(await client.query("SELECT schemaname,tablename FROM pg_tables WHERE schemaname IN ('public','simulation_private') ORDER BY schemaname,tablename")).rows;
 const counts={};for(const t of tables)counts[`${t.schemaname}.${t.tablename}`]=(await client.query(`SELECT count(*)::text n FROM ${qi(t.schemaname)}.${qi(t.tablename)}`)).rows[0].n;
 const scores=(await client.query('SELECT count(*)::text n,sum(sequence)::text sequences,sum(clock_seconds)::text clocks,sum(home_score)::text home,sum(away_score)::text away FROM events')).rows[0];
 return {counts,scores};
}
async function command(args,{input,output,env={}}={}){
 const child=spawn('docker',args,{cwd:root,env:{...process.env,...env},stdio:[input?'pipe':'ignore',output?'pipe':'ignore','pipe']});
 let stderr='';child.stderr.on('data',b=>{stderr=(stderr+b.toString()).slice(-6000);});
 const completion=new Promise((resolve,reject)=>{child.on('error',reject);child.on('close',code=>code===0?resolve():reject(new Error(`Database utility exited ${code}: ${stderr}`)));});
 const streams=[];
 if(input)streams.push(pipeline(createReadStream(input),child.stdin));
 if(output)streams.push(pipeline(child.stdout,createWriteStream(output,{mode:0o600})));
 await Promise.all([completion,...streams]);
}
